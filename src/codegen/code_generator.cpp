#include "code_generator.h"
#include "../model/petrinet.h"
#include <fstream>
#include <sstream>
#include <cstdlib>

namespace pets {

bool CodeGenerator::generate(const PetriNet& net, const std::string& output_path)
{
    std::ofstream out(output_path);
    if (!out.is_open()) {
        return false;
    }

    // Hlavička
    out << generate_header(net);

    // Vestavěné funkce
    out << generate_builtins();

    // Stráže pro každý přechod
    for (const auto& t : net.transitions) {
        if (t.has_guard()) {
            out << generate_guard(t) << "\n";
        }
    }

    // Akce pro každý přechod
    for (const auto& t : net.transitions) {
        if (t.action_code.has_value()) {
            out << generate_action("action_" + t.id, t.action_code.value()) << "\n";
        }
    }

    // Place actions
    for (const auto& p : net.places) {
        if (p.place_action.has_value()) {
            out << generate_action("place_action_" + p.id, p.place_action.value()) << "\n";
        }
    }

    out.close();
    return true;
}

bool CodeGenerator::compile(const std::string& source_path, const std::string& lib_path)
{
#ifdef _WIN32
    std::string cmd = "g++ -std=c++17 -shared -O2 -o " + lib_path + " " + source_path;
#else
    std::string cmd = "g++ -std=c++17 -shared -fPIC -O2 -o " + lib_path + " " + source_path;
#endif
    return std::system(cmd.c_str()) == 0;
}

std::string CodeGenerator::generate_header(const PetriNet& net) const
{
    std::ostringstream ss;
    ss << "// Auto-generated code for Petri net: " << net.name << "\n";
    ss << "// Generated by pets::CodeGenerator\n";
    ss << "// DO NOT EDIT MANUALLY\n";
    ss << "\n";
    ss << "#include <cstdint>\n";
    ss << "#include <cstring>\n";
    ss << "#include <cstdlib>\n";
    ss << "#include <string>\n";
    ss << "\n";
    ss << "// Callback typy – implementováno v interpreteru\n";
    ss << "extern \"C\" {\n";
    ss << "\n";
    ss << "// Tyto proměnné nastavuje interpreter před každým voláním\n";

    // Deklarace extern proměnných pro valueof / defined / tokens / elapsed
    for (const auto& i : net.inputs) {
        ss << "extern const char* valueof_" << i.name << ";\n";
        ss << "extern bool       defined_" << i.name << ";\n";
    }
    for (const auto& p : net.places) {
        ss << "extern int  tokens_" << p.id << ";\n";
        ss << "extern int  elapsed_" << p.id << ";\n";
    }
    for (const auto& v : net.variables) {
        ss << "extern " << v.type << " var_" << v.name << ";\n";
    }
    ss << "extern int64_t now_ms;\n";
    ss << "\n";

    // Deklarace output funkce
    ss << "extern void output_func(const char* name, const char* value);\n";
    ss << "\n";
    ss << "} // extern \"C\"\n";
    ss << "\n";

    return ss.str();
}

std::string CodeGenerator::generate_builtins() const
{
    // Vestavěné funkce jsou mapovány přímo na extern proměnné –
    // interpreter je nastaví před každým voláním.
    // Tady jen placeholder – v ostré verzi lze přidat wrapper funkce.
    return "// Builtins: valueof, defined, tokens, elapsed, now, output\n"
           "// (implementovány jako inline přístupy k extern proměnným)\n\n";
}

std::string CodeGenerator::generate_guard(const Transition& t) const
{
    std::ostringstream ss;
    ss << "extern \"C\" bool guard_" << t.id << "()\n";
    ss << "{\n";
    ss << "    return (" << t.guard_expression.value() << ");\n";
    ss << "}\n";
    return ss.str();
}

std::string CodeGenerator::generate_action(const std::string& func_name,
                                            const std::string& action_code) const
{
    std::ostringstream ss;
    ss << "extern \"C\" void " << func_name << "()\n";
    ss << "{\n";
    ss << "    " << action_code << "\n";
    ss << "}\n";
    return ss.str();
}

} // namespace pets
